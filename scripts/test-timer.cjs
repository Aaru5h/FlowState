const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const cache = new Map();
let saved;
global.window = {};
global.localStorage = { getItem: () => saved ?? null, setItem: (_, value) => { saved = value; } };
function load(path) {
  if (cache.has(path)) return cache.get(path);
  const module = { exports: {} };
  const code = ts.transpileModule(fs.readFileSync(path, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
  vm.runInThisContext(`(function(require, module, exports) { ${code}\n})`)(
    (name) => name.startsWith('@/') ? load(`src/${name.slice(2)}.ts`) : require(name), module, module.exports);
  cache.set(path, module.exports);
  return module.exports;
}
