const now = new Date(2026, 9, 11, 12);
assert.equal(stats.periodStats(history, 'day', now).totalFocusSeconds, 1200);
assert.equal(stats.periodStats(history, 'week', now).totalFocusSeconds, 1800);
assert.equal(stats.periodStats(history, 'month', now).totalFocusSeconds, 1800);
assert.equal(stats.periodStats(stats.updateDay(history, '2026-09-30', { sessions: 7 }), 'month', now).sessions, 0);
